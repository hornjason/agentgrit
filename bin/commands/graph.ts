function showStats(base: string): void {
  const graphPath = join(base, "state", "knowledge-graph.json");
  if (!existsSync(graphPath)) {
    console.log("  No graph found. Run 'agentgrit graph build' first.\n");
    return;
  }

  const graph = readGraph();
  console.log(`  Nodes:   ${graph.nodeCount}`);
  console.log(`  Edges:   ${graph.edgeCount}`);
  console.log(`  Built:   ${relativeTime(graph.builtAt)}`);

  const domains = new Map<string, number>();
  for (const node of Object.values(graph.nodes)) {
    for (const d of node.domains) {
      domains.set(d, (domains.get(d) ?? 0) + 1);
    }
  }

  if (domains.size > 0) {
    console.log(`  Domains: ${domains.size}`);
    const sorted = [...domains.entries()].sort((a, b) => b[1] - a[1]);
    for (const [domain, count] of sorted.slice(0, 10)) {
      console.log(`    ${domain.padEnd(20)} ${count} nodes`);
    }
    if (sorted.length > 10) {
      console.log(`    ... and ${sorted.length - 10} more`);
    }
  }
}

async function doBuild(base: string, full: boolean): Promise<void> {
  const memoryDir = resolveMemoryDir();
  console.log(`  Building graph${full ? " (full)" : " (incremental)"}...`);
  const graph = await buildGraph(memoryDir, join(base, "state"));
  console.log(`  ✓ Built: ${graph.nodeCount} nodes, ${graph.edgeCount} edges`);
}

function doQuery(base: string, queryStr: string): void {
  const graph = readGraph();
  if (graph.nodeCount === 0) {
    console.log("  Empty graph. Run 'agentgrit graph build' first.\n");
    return;
  }

  const domains = queryStr.split(",").map((d) => d.trim()).filter(Boolean);
  const clusters = queryGraph(graph, domains, 5);

  if (clusters.length === 0) {
    console.log(`  No clusters found for domains: ${domains.join(", ")}\n`);
    return;
  }

  console.log(`  ${clusters.length} cluster(s) for: ${domains.join(", ")}\n`);
  for (const cluster of clusters) {
    const text = cluster.primary.ruleText?.slice(0, 80) ?? "";
    console.log(`  [${cluster.score.toFixed(3)}] ${cluster.primary.id}`);
    console.log(`         ${text}`);
    console.log(`         domains: ${cluster.domains.join(", ")}`);
    if (cluster.connected.length > 0) {
      console.log(`         connected: ${cluster.connected.map((c) => c.node.id).join(", ")}`);
    }
  }
}

function doReport(): void {
  const graph = readGraph();
  if (graph.nodeCount === 0) {
    console.log("  Empty graph. Run 'agentgrit graph build' first.\n");
    return;
  }
  const report = generateReport(graph);
  console.log(formatReportMarkdown(report));
}

export async function graphCommand(args: string[]): Promise<void> {
  const base = getBaseDir();
  const sub = args[0];

  console.log("\nagentgrit graph\n");

  if (!existsSync(base)) {
    console.log("  agentgrit not initialized. Run 'agentgrit init' first.\n");
    return;
  }

  if (sub === "build") {
    await doBuild(base, args.includes("--full"));
    try {
      const { generateShowcase } = await import("./showcase");
      await generateShowcase();
    } catch {
      // showcase regeneration is non-critical
    }
  } else if (sub === "classify") {
    const { readGraph } = await import("../../src/graph/builder");
    const { classifyIsolatedNodes } = await import("../../src/graph/classify-isolated");
    const graph = readGraph();
    const isolated = Object.values(graph.nodes).filter(n => n.domains.length === 0);
    console.log(`  Isolated nodes (zero domains): ${isolated.length}`);
    if (isolated.length === 0) {
      console.log("  Nothing to classify.");
      return;
    }
    const max = args.includes("--max") ? parseInt(args[args.indexOf("--max") + 1]) || 20 : 20;
    const results = await classifyIsolatedNodes(graph, { maxNodes: max });
    console.log(`  Classified: ${results.length} node(s)`);
    for (const r of results) {
      console.log(`    ${r.nodeId} → ${r.domains.join(", ")}`);
    }
  } else if (sub === "auto-domains") {
    const { readGraph } = await import("../../src/graph/builder");
    const { autoGenerateDomains } = await import("../../src/graph/auto-domains");
    const graph = readGraph();
    if (graph.nodeCount === 0) {
      console.log("  Empty graph. Run 'agentgrit graph build' first.");
      return;
    }
    const max = args.includes("--max") ? parseInt(args[args.indexOf("--max") + 1]) || 50 : 50;
    const dryRun = args.includes("--dry-run");
    const force = args.includes("--force");
    console.log(`  Auto-classifying nodes${dryRun ? " (dry run)" : ""}${force ? " (force)" : ""}...`);
    const result = await autoGenerateDomains(graph, { maxNodes: max, dryRun, force });
    console.log(`  Total nodes: ${result.total}`);
    console.log(`  Classified:  ${result.classified}`);
    console.log(`  Skipped:     ${result.skipped}`);
    for (const entry of result.entries) {
      console.log(`    ${entry.nodeId} -> ${entry.domains.join(", ")} (${entry.method})`);
    }
    if (result.errors.length > 0) {
      console.log(`  Errors: ${result.errors.join(", ")}`);
    }
  } else if (sub === "query") {
    const query = args.slice(1).join(" ");
    if (!query) {
      console.log("  Usage: agentgrit graph query <domains>\n");
      return;
    }
    doQuery(base, query);
  } else if (sub === "report") {
    doReport();
  } else if (sub === "context") {
    const graph = readGraph();
    if (graph.nodeCount === 0) {
      console.log("  Empty graph. Run 'agentgrit graph build' first.\n");
      return;
    }
    const memoryDir = resolveMemoryDir();
    const index = buildIndexFromDir(memoryDir);
    const queryIdx = args.indexOf("--query");
    const queryText = queryIdx !== -1 && args[queryIdx + 1] ? args.slice(queryIdx + 1).join(" ") : "";
    const signalDir = resolveSignalDir();
    let domains = queryText ? detectDomains(queryText) : [];
    const workDomains = await getWorkContextDomains(signalDir);
    for (const wd of workDomains) {
      if (!domains.includes(wd)) domains.push(wd);
    }
    const rules = await getContextRules(graph, index, domains, 10, signalDir, queryText || undefined);
    const rulesText = rules.map(r => `- **${r.id}:** ${r.text}`).join("\n");

    const extraSections: string[] = [];
    const perf = await computePerformanceSummary(signalDir);
    if (perf) {
      const fmt = (v: number | null) => v !== null ? `${v.toFixed(1)}/10` : "—";
      extraSections.push(`\n**Performance Signals:** Today: ${fmt(perf.today_avg)} | Week: ${fmt(perf.week_avg)} | Month: ${fmt(perf.month_avg)} | Trend: ${perf.trend} | Total signals: ${perf.total_signals}`);
    }
    const failures = await getRecentFailurePatterns(signalDir);
    if (failures.length > 0) {
      extraSections.push(`\n**Recent Failure Patterns (avoid these):**\n${failures.map(f => `  ${f}`).join("\n")}`);
    }

    const contextOutput = `<system-reminder>\nAgentGrit Context (auto-loaded)\n\n${rulesText}${extraSections.join("")}\n</system-reminder>`;
    console.log(contextOutput);
    const totalContextLines = contextOutput.split("\n").length;
    writeSessionContext(rules, domains.length > 0 ? domains : ["default"], "keyword", totalContextLines);
  } else if (sub === "stats") {
    showStats(base);
  } else {
    showStats(base);
  }

  console.log("");
}
